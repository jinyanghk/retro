#!/usr/bin/env python3
import os, sys, glob

def embed_file(path):
    with open(path, 'r', encoding='utf-8') as f:
        content = f.read()
    return f'R"GLSL({content})GLSL"'

def main():
    src_dir = sys.argv[1]
    out_file = sys.argv[2]
    
    files = sorted(glob.glob(os.path.join(src_dir, '*.vert')) +
                   glob.glob(os.path.join(src_dir, '*.frag')))
    
    lines = ['// AUTO-GENERATED by tools/embed_shaders.py. DO NOT EDIT.', '#pragma once', '']
    lines.append('namespace Shaders {')
    for f in files:
        name = os.path.splitext(os.path.basename(f))[0]
        ext  = os.path.splitext(f)[1][1:]
        var  = f'{name}_{ext}'
        lines.append(f'static const char* {var} = {embed_file(f)};')
    lines.append('}')
    
    with open(out_file, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'[embed_shaders] wrote {out_file} ({len(files)} shaders)')

if __name__ == '__main__':
    main()